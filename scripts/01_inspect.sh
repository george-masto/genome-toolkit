#!/usr/bin/env bash
# ============================================================================
# 01_inspect.sh — characterize every input file: sizes, formats, read length,
# reference build, contig naming, sample id, caller versions.
#
# Writes a Markdown inventory to analysis/01_data_inventory.md (gitignored,
# since it names per-sample files). Safe summary also printed to the terminal.
# ============================================================================
source "$(dirname "$0")/lib/common.sh"
require_tool bcftools

OUT="$OUT_DIR/01_data_inventory.md"
show_inputs

{
  echo "# Data inventory"
  echo
  echo "_Generated by 01_inspect.sh. Gitignored — contains per-sample filenames._"
  echo
  echo "| Property | Value |"
  echo "|---|---|"
  echo "| Sample | \`$(sample_name)\` |"
  echo "| Reference | $(ref_build) |"
  echo "| Contig style | \"$(chrom_prefix)\"-prefixed |"
  echo

  echo "## Files"
  echo
  echo "| File | Size | Format |"
  echo "|---|---|---|"
  for f in "$FASTQ_R1" "$FASTQ_R2" "$VCF_SNP" "$VCF_CNV" "$VCF_SV"; do
    [[ -n "$f" && -f "$f" ]] || continue
    sz=$(du -h "$f" | cut -f1)
    fmt=$(htsfile "$f" 2>/dev/null | sed 's/^[^:]*:[[:space:]]*//')
    printf '| `%s` | %s | %s |\n' "$(basename "$f")" "$sz" "$fmt"
  done
  echo
} > "$OUT"

# --- FASTQ specifics --------------------------------------------------------
if [[ -n "$FASTQ_R1" && -f "$FASTQ_R1" ]]; then
  log "Inspecting FASTQ R1 (reading first reads only)…"
  # head -2 terminates the gzcat stream early (avoid decompressing the whole file).
  # Portable to bash 3.2 (macOS) — no mapfile.
  { read -r rname; read -r _rseq; } < <(gzcat "$FASTQ_R1" 2>/dev/null | head -2)
  rlen="${#_rseq}"
  {
    echo "## Raw reads"
    echo
    echo "- First read name: \`$rname\`"
    echo "- Read length: ${rlen} bp"
    echo "- Layout: paired-end (R1 + R2)"
    echo
  } >> "$OUT"
  ok "Read length ${rlen}bp; first read $rname"
fi

# --- VCF specifics: caller, variant count estimate --------------------------
inspect_vcf() {
  local label="$1" vcf="$2"
  [[ -n "$vcf" && -f "$vcf" ]] || return 0
  log "Inspecting $label VCF…"
  local src contigs
  src=$(bcftools view -h "$vcf" | grep '^##source=' | sed 's/##source=//' | paste -sd'; ' -)
  contigs=$(bcftools view -h "$vcf" | grep -c '^##contig=' || true)
  {
    echo "## $label VCF"
    echo
    echo "- Caller / source: $src"
    echo "- Contigs declared: $contigs"
    echo
  } >> "$OUT"
  ok "$label: $src"
}
inspect_vcf "SNP/indel" "$VCF_SNP"
inspect_vcf "CNV"       "$VCF_CNV"
inspect_vcf "SV"        "$VCF_SV"

ok "Inventory written to $OUT"
