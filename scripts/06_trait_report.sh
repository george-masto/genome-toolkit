#!/usr/bin/env bash
# ============================================================================
# 06_trait_report.sh — your genotype at a curated set of well-known variants.
#
# Reads assets/traits/known_variants.tsv (public reference data), resolves each
# rsID against YOUR variants file (authoritative), computes how many copies of
# each effect allele you carry, and writes a readable report.
#
# Output: analysis/06_trait_report.md  (gitignored — it's your genotype).
#
# ⚠️  EDUCATIONAL ONLY. Not medical advice, not a diagnosis. Single-variant
#     associations are simplifications. Talk to a clinician or genetic
#     counselor before acting on anything here.
#
# Run 03_extract_variants.sh first.
# ============================================================================
source "$(dirname "$0")/lib/common.sh"
require_tool bcftools

VARIANTS="${VARIANTS:-$OUT_DIR/variants.vcf.gz}"
CATALOG="${CATALOG:-$ASSETS_DIR/traits/known_variants.tsv}"
REPORT="$OUT_DIR/06_trait_report.md"
[[ -f "$VARIANTS" ]] || die "Missing $VARIANTS — run scripts/03_extract_variants.sh first."
[[ -f "$CATALOG"  ]] || die "Missing catalog $CATALOG"

# 1) collect catalog rsIDs
rsfile="$(mktemp)"; foundfile="$(mktemp)"
trap 'rm -f "$rsfile" "$foundfile"' EXIT
grep -v '^#' "$CATALOG" | awk -F'\t' 'NF>=10{print $1}' > "$rsfile"
n_cat=$(wc -l < "$rsfile" | tr -d ' ')
log "Resolving $n_cat catalog variants against your genome (one scan)…"

# 2) single pass over the variants file pulling just those rsIDs
bcftools view "$VARIANTS" 2>/dev/null \
  | bcftools query -i "ID=@$rsfile" \
      -f '%ID\t%REF\t%ALT\t[%GT]\t[%DP]\t%CHROM\t%POS\n' 2>/dev/null \
  > "$foundfile" || true
n_found=$(wc -l < "$foundfile" | tr -d ' ')
ok "$n_found of $n_cat catalog sites present as variants (rest = homozygous reference)"

# 3) merge + interpret with awk, emit markdown grouped by category
SAMPLE="$(sample_name)"; BUILD="$(ref_build)"
awk -F'\t' -v sample="$SAMPLE" -v build="$BUILD" '
function base(i, dref, dalt) { return (i==0)?dref : (i==1)?dalt : "?" }
FNR==NR {                      # first file = foundfile
  if ($1=="") next
  fREF[$1]=$2; fALT[$1]=$3; fGT[$1]=$4; fDP[$1]=$5; fCHR[$1]=$6; fPOS[$1]=$7; have[$1]=1
  next
}
/^#/ { next }
NF < 10 { next }
{
  rsid=$1; gene=$2; tref=$5; talt=$6; eff=$7; cat=$8; trait=$9; effect=$10
  mism=""
  if (rsid in have) {
    dref=fREF[rsid]; dalt=fALT[rsid]; gt=fGT[rsid]; dp=fDP[rsid]
    n=split(gt, a, /[\/|]/)
    if (a[1]==".") { geno="no-call"; copies="?" }
    else {
      b1=base(a[1],dref,dalt); b2=base(a[2],dref,dalt)
      geno=b1 "/" b2
      copies=(b1==eff)+(b2==eff)
    }
    if (dref!=tref || dalt!=talt) mism=" ⚠️(catalog "tref">"talt", data "dref">"dalt")"
  } else {
    geno=tref "/" tref; dp="(hom-ref)"; copies=(tref==eff)?2:0
  }
  cz=(copies=="?")?"?":(copies==2?"2 — homozygous":(copies==1?"1 — heterozygous":"0"))
  row=sprintf("| %s | %s | **%s** | %s | %s%s |", gene, rsid, geno, cz, trait, mism)
  note=sprintf("- **%s (%s)** — your genotype **%s**, %s copies of `%s`: %s", gene, rsid, geno, copies, eff, effect)
  if (!(cat in catseen)) { catorder[++ncat]=cat; catseen[cat]=1 }
  rows[cat]=rows[cat] row "\n"
  notes[cat]=notes[cat] note "\n"
}
END {
  print "# Trait & pharmacogenomic report — " sample
  print ""
  print "_Reference build: " build ". Generated by 06_trait_report.sh. Gitignored._"
  print ""
  print "> ⚠️ **Educational only — not medical advice.** These are statistical"
  print "> associations from single variants, not diagnoses. Effects can depend"
  print "> on ancestry, other genes, and environment. Consult a clinician or"
  print "> genetic counselor before acting on anything here."
  print ""
  print "Effect alleles are the derived/ALT allele, so \"0 copies\" = the common genotype."
  print ""
  for (i=1;i<=ncat;i++){
    c=catorder[i]
    print "## " c
    print ""
    print "| Gene | Variant | Your genotype | Effect-allele copies | Association |"
    print "|---|---|---|---|---|"
    printf "%s", rows[c]
    print ""
    print "<details><summary>details</summary>"
    print ""
    printf "%s", notes[c]
    print ""
    print "</details>"
    print ""
  }
}
' "$foundfile" "$CATALOG" > "$REPORT"

ok "Wrote $REPORT"
hr
cat "$REPORT" >&2
